import { afterAll, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { categorize, categoryByPath } from "./categories";

test("conventions: lockfiles and snapshots are generated, tests and docs by name and place", () => {
  expect(categoryByPath("bun.lock")).toBe("generated");
  expect(categoryByPath("web/__snapshots__/a.snap")).toBe("generated");
  expect(categoryByPath("src/pay.test.ts")).toBe("test");
  expect(categoryByPath("apps/x/__tests__/a.ts")).toBe("test");
  expect(categoryByPath("docs/intro.mdx")).toBe("docs");
  expect(categoryByPath("src/pay.ts")).toBeNull();
});

const repo = mkdtempSync(join(tmpdir(), "nit-cat-"));
afterAll(() => rmSync(repo, { recursive: true, force: true }));

test(".gitattributes wins, and a generated header counts", async () => {
  const write = (p: string, s: string) => {
    mkdirSync(dirname(join(repo, p)), { recursive: true });
    writeFileSync(join(repo, p), s);
  };
  Bun.spawnSync(["git", "init", "-q"], { cwd: repo });
  write(
    ".gitattributes",
    "packages/db/types.ts linguist-generated\ncheck/*.ts review-test\nREADME.md -linguist-documentation\n",
  );
  write("packages/db/types.ts", "export type A = 1;\n");
  write("check/x.ts", "x\n");
  write("src/schema.ts", "// @generated by prisma\nexport {}\n");
  write("src/pay.ts", "export const pay = 1;\n");
  write("README.md", "# hi\n");
  const c = await categorize(repo, ["packages/db/types.ts", "check/x.ts", "src/schema.ts", "src/pay.ts", "README.md"]);
  expect(c).toEqual({
    "packages/db/types.ts": "generated",
    "check/x.ts": "test",
    "src/schema.ts": "generated",
    // README.md is -linguist-documentation: the repo says it isn't docs, so the name doesn't decide
  });
});
