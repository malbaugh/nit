import type { FileCategory } from "./types";

/**
 * What kind of file each changed path is, so the review can set aside what isn't the change
 * itself. The repo says first, through .gitattributes (GitHub's linguist-generated,
 * linguist-vendored and linguist-documentation, and the review-test / review-documentation
 * attributes Linear reads); common conventions fill in the rest.
 */
const ATTRS = [
  "linguist-generated",
  "linguist-vendored",
  "linguist-documentation",
  "review-test",
  "review-documentation",
];

const LOCKFILES = new Set([
  "bun.lock",
  "bun.lockb",
  "package-lock.json",
  "pnpm-lock.yaml",
  "yarn.lock",
  "Cargo.lock",
  "go.sum",
  "Gemfile.lock",
  "poetry.lock",
  "composer.lock",
  "uv.lock",
]);

/** By name and place alone, when .gitattributes doesn't say. */
export function categoryByPath(path: string): FileCategory | null {
  const name = path.slice(path.lastIndexOf("/") + 1);
  if (
    LOCKFILES.has(name) ||
    /\.(min\.(js|css)|map|snap)$/.test(name) ||
    /(^|\/)(__generated__|generated|__snapshots__)\//.test(path) ||
    /\.generated\.\w+$/.test(name)
  )
    return "generated";
  if (
    /\.(test|spec)\.[cm]?[jt]sx?$/.test(name) ||
    /(^|\/)(__tests__|tests?|spec|e2e)\//.test(path) ||
    /_test\.(go|py|rb)$/.test(name) ||
    /^test_.*\.py$/.test(name)
  )
    return "test";
  if (/(^|\/)docs?\//.test(path) || /\.(md|mdx|rst|adoc)$/.test(name)) return "docs";
  return null;
}

/** A file whose first lines say a tool wrote it. */
const generatedHeader = (head: string) => /@generated|do not edit|auto-?generated|code generated by/i.test(head);

export async function categorize(root: string, paths: string[]): Promise<Record<string, FileCategory>> {
  const out: Record<string, FileCategory> = {};
  if (!paths.length) return out;
  // `git check-attr -z --stdin`: path, attribute, value, NUL-separated.
  const proc = Bun.spawn(["git", "check-attr", "-z", "--stdin", ...ATTRS], {
    cwd: root,
    stdin: "pipe",
    stdout: "pipe",
  });
  proc.stdin.write(paths.map((p) => `${p}\0`).join(""));
  await proc.stdin.end();
  const fields = (await new Response(proc.stdout).text()).split("\0");
  const attrs = new Map<string, Map<string, string>>();
  for (let i = 0; i + 2 < fields.length; i += 3) {
    const [path, attr, value] = [fields[i], fields[i + 1], fields[i + 2]];
    if (value !== "unspecified") attrs.set(path, (attrs.get(path) ?? new Map()).set(attr, value));
  }
  const on = (path: string, attr: string) => {
    const v = attrs.get(path)?.get(attr);
    return v !== undefined && v !== "unset" && v !== "false";
  };
  const off = (path: string, attr: string) => ["unset", "false"].includes(attrs.get(path)?.get(attr) ?? "");
  // A category the repo turns off (-linguist-generated, -review-test, -linguist-documentation)
  // isn't guessed back on.
  const denied = (path: string, c: FileCategory) =>
    c === "generated"
      ? off(path, "linguist-generated")
      : c === "test"
        ? off(path, "review-test")
        : off(path, "linguist-documentation") || off(path, "review-documentation");
  for (const path of paths) {
    if (on(path, "linguist-generated") || on(path, "linguist-vendored")) out[path] = "generated";
    else if (on(path, "review-test")) out[path] = "test";
    else if (on(path, "linguist-documentation") || on(path, "review-documentation")) out[path] = "docs";
    else {
      let guess = categoryByPath(path);
      if (!guess) {
        const head = await Bun.file(`${root}/${path}`)
          .slice(0, 600)
          .text()
          .catch(() => "");
        if (generatedHeader(head)) guess = "generated";
      }
      if (guess && !denied(path, guess)) out[path] = guess;
    }
  }
  return out;
}
